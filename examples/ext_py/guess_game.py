# -*- coding: utf-8 -*-
"""终端猜数字小游戏：Python 域游戏引擎（声明式导出）。

供 VUS 侧 导入外部 (游戏, {源: "ext_py.guess_game"}) 调用：
- 生成秘密(): 1..上限 随机整数（出题）
- 中点(下限, 上限): 二分查找中点（整数）
- 判断(秘密, 猜测): 反馈 大了/小了/恭喜猜中（裁判）
- 回合数/最高分: 导出变量，VUS 结算时写回；上限 只读
"""

import random

__vus_export__ = {
    "函数": ["生成秘密", "中点", "判断"],
    "变量": ["回合数", "最高分"],
    "只读": ["上限"],
}

上限 = 100
回合数 = 0
最高分 = 0


def 生成秘密():
    """出题：返回 1..上限 的随机整数。"""
    return random.randint(1, 上限)


def 中点(下限, 上限):
    """二分中点（向下取整），供 VUS 主循环逐轮收窄区间。"""
    return (int(下限) + int(上限)) // 2


def 判断(秘密, 猜测):
    """裁判：返回 大了/小了/恭喜猜中（VUS 侧按字符串分支）。"""
    秘密 = int(秘密)
    猜测 = int(猜测)
    if 猜测 > 秘密:
        return "大了"
    if 猜测 < 秘密:
        return "小了"
    return "恭喜猜中"
