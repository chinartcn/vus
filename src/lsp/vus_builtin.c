const VusBuiltin *vus_builtin_table(void) {
    return g_builtins;
}

int vus_builtin_count(void) {
    static int count = -1;
    if (count < 0) {
        count = 0;
        while (g_builtins[count].name) count++;
    }
    return count;
}

const VusBuiltin *vus_builtin_find(const char *name) {
    if (!name) return NULL;
    for (int i = 0; g_builtins[i].name; i++) {
        if (strcmp(g_builtins[i].name, name) == 0)
            return &g_builtins[i];
    }
    return NULL;
}